@Composable
internal fun cafeJournalAccount(value: String): String {
    val code = value.substringBefore(' ')
    val name = value.substringAfter(' ', "")
    return if (code.length == 4 && code.all(Char::isDigit) && name.isNotBlank()) {
        "$code ${cafeLabel(name)}"
    } else cafeLabel(value)
}
